  "근속연수(그룹입사일)", "근속연수(입사일)",
  "발령명", "입사경로", "추천인", "인정경력(년)", "인정경력(월)",
  "성별", "생년월일", "나이(만)", "결혼여부", "음양구분", "생일",
  "학력", "학교", "학위", "전공",
